"""Thrust-vector decomposition mu -> (f_T, Theta_r, omega_r): the outer-to-inner loop link [Eng] (A15, D30).

The paper (Sec. V) uses a reference attitude Theta_r and rate omega_r generated by an "unknown" chi_j, but does
not say how they follow from the visual-servoing input mu. D30 uses the standard decomposition:

    F       = mu + m g e3                      [Eng] D14: mu is the deviation from hover
    f_T     = ||F||                            eq. (1): the physical thrust vector is f_T R e3 = F
    b       = F / ||F||                        required body axis R e3
    b_bar   = Rz(psi_r)^T b = [sin(th) cos(ph), -sin(ph), cos(th) cos(ph)]   (ZYX, A13)
    phi_r   = arcsin(-b_bar_y),  theta_r = atan2(b_bar_x, b_bar_z),  psi_r = 0 (Fig. 8, D30)
    omega_r = W(Theta_r)^-1 d/dt Theta_r       body rate of the reference; d/dt by the D20 filter

Frames: mu, F in the inertial frame eF with e3 pointing down (A12); omega_r in the body frame.
With ||mu|| <= beta < m g (D14), F_z >= m g - beta > 0, so f_T > 0, the vehicle stays upright and the tilt
is at most arcsin(beta / (m g)) (23.1 deg for Quad 2, 14.8 deg for Quad 3; E11).
This module realises chi_j numerically; the learner never needs it in closed form.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from vsfc.differentiator import FilteredDifferentiator
from vsfc.dynamics import E3, euler_rate_matrix


def wrap_angle(a):
    """Wrap angle(s) to (-pi, pi]. Used for the yaw tracking error (Fig. 8)."""
    return np.pi - np.mod(np.pi - np.asarray(a, float), 2.0 * np.pi)


def thrust_vector(mu: np.ndarray, mass: float, g: float) -> np.ndarray:
    """[Eng] D14: physical thrust vector F = f_T R e3 = mu + m g e3, (3,) N, inertial frame."""
    return np.asarray(mu, float) + mass * g * E3


def decompose_thrust(F: np.ndarray, psi_r: float = 0.0) -> tuple[float, np.ndarray]:
    """[Eng] D30: F (3,) N -> (f_T in N, Theta_r = [phi_r, theta_r, psi_r] in rad, ZYX).

    Exact inverse of F = f_T R(Theta_r) e3 for the given yaw. Requires an upright command
    (body axis within 90 deg of e3 after removing yaw); raises ValueError otherwise.
    """
    F = np.asarray(F, float)
    f_T = float(np.linalg.norm(F))
    if f_T == 0.0:
        raise ValueError("zero thrust vector: attitude undefined")
    b = F / f_T
    c, s = np.cos(psi_r), np.sin(psi_r)
    bx, by, bz = c * b[0] + s * b[1], -s * b[0] + c * b[1], b[2]     # Rz(psi_r)^T b
    if not bz > 0.0:
        raise ValueError(f"thrust vector not upright (b_z = {bz:.3g}); |mu| < m g is required (D14)")
    phi_r = np.arcsin(np.clip(-by, -1.0, 1.0))
    theta_r = np.arctan2(bx, bz)
    return f_T, np.array([phi_r, theta_r, float(psi_r)])


def thrust_mapping(mu: np.ndarray, mass: float, g: float, psi_r: float = 0.0) -> tuple[float, np.ndarray]:
    """[Eng] D14 + D30: mu (3,) N -> (f_T, Theta_r)."""
    return decompose_thrust(thrust_vector(mu, mass, g), psi_r)


def tracking_error(theta: np.ndarray, omega: np.ndarray, theta_r: np.ndarray,
                   omega_r: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """[Eng] D29 error coordinates: e_Theta = wrap(Theta - Theta_r) (rad), e_omega = omega - omega_r (rad/s)."""
    e_theta = wrap_angle(np.asarray(theta, float) - np.asarray(theta_r, float))
    return e_theta, np.asarray(omega, float) - np.asarray(omega_r, float)


def tracking_error_euler_rate(theta: np.ndarray, omega: np.ndarray, theta_r: np.ndarray,
                              theta_r_dot: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """[Eng] D33 (revises D29's rate error): e_Theta = wrap(Theta - Theta_r) (rad) and the EULER-RATE error
    e_omega = W(Theta) omega - Theta_r_dot = Theta_dot - Theta_r_dot (rad/s), so e_Theta_dot = e_omega exactly.

    Under the paper's model (33), Theta_dot = omega, this equals omega - omega_r. On the exact plant (1) the body-rate
    error couples the axes through W(Theta) and breaks the per-axis learning problem (E13)."""
    e_theta = wrap_angle(np.asarray(theta, float) - np.asarray(theta_r, float))
    return e_theta, euler_rate_matrix(theta) @ np.asarray(omega, float) - np.asarray(theta_r_dot, float)


@dataclass(frozen=True)
class AttitudeReference:
    """Output of the reference generator at one sample."""

    f_T: float                  # N
    theta_r: np.ndarray         # (3,) rad, ZYX
    theta_r_dot: np.ndarray     # (3,) rad/s, filtered Euler-angle rates
    omega_r: np.ndarray         # (3,) rad/s, body frame


class ReferenceGenerator:
    """Numerical chi_j (Sec. V, eq. (33)) [Eng] D30: samples of mu -> f_T, Theta_r, omega_r.

    mass: kg; g: m/s^2; dt: sample period of mu (s); tau: rate-filter time constant (s); psi_r: rad.
    psi_r is constant, so Theta_r never wraps and can be differentiated directly.
    """

    def __init__(self, mass: float, g: float, dt: float, tau: float, psi_r: float = 0.0):
        self.mass, self.g, self.psi_r = float(mass), float(g), float(psi_r)
        self._diff = FilteredDifferentiator(dt, tau)
        self._ready = False

    @classmethod
    def from_case_study(cls, case, follower, dt: float | None = None) -> "ReferenceGenerator":
        """Build from config: m_j, g, psi_ref, ref_rate_tau; dt defaults to the simulation step."""
        return cls(follower.mass, case.g, case.step if dt is None else dt, case.ref_rate_tau, case.psi_ref)

    def _output(self, f_T: float, theta_r: np.ndarray, theta_r_dot: np.ndarray) -> AttitudeReference:
        omega_r = np.linalg.solve(euler_rate_matrix(theta_r), theta_r_dot)
        return AttitudeReference(f_T, theta_r, theta_r_dot, omega_r)

    def reset(self, mu0: np.ndarray, theta_r_dot0: np.ndarray | None = None) -> AttitudeReference:
        """Start from the first input sample; initial rate estimate theta_r_dot0 (default 0)."""
        f_T, theta_r = thrust_mapping(mu0, self.mass, self.g, self.psi_r)
        rate = self._diff.reset(theta_r, theta_r_dot0)
        self._ready = True
        return self._output(f_T, theta_r, rate)

    def update(self, mu: np.ndarray) -> AttitudeReference:
        """Feed the next mu sample (dt after the previous one)."""
        if not self._ready:
            raise RuntimeError("call reset() before update()")
        f_T, theta_r = thrust_mapping(mu, self.mass, self.g, self.psi_r)
        return self._output(f_T, theta_r, self._diff.update(theta_r))
